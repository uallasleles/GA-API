    LONGITUDE,
    DATAHORA,
    OBS_MOTORISTA,
    ROMANEIO_ID,
    DATA_REGISTRO,
    ENTREGA_ID,
    MOTIVO_DEVOL_REENT_ID,
    MOTORISTA_ID,
